import SwiftUI
import Defaults

func loc(_ key: String) -> String {
    L10n.tr(key)
}

func loc(_ format: String, _ arguments: CVarArg...) -> String {
    let translatedFormat = L10n.tr(format)
    return String(format: translatedFormat, arguments: arguments)
}

